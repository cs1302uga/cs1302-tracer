#!/usr/bin/env python3
"""Generate or check license and dependency pages from fresh Maven resolution."""

import argparse
import difflib
import hashlib
import html
import json
import re
import subprocess
import tempfile
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
MISSING = "Not declared in upstream metadata"
GROUPS = {"compile": "Runtime", "runtime": "Runtime", "test": "Test", "provided": "Provided", "system": "System"}
NOTICE = "<!-- Generated by scripts/dependency_docs.py; edit upstream inputs, then run update. -->\n"


def string(value: object, label: str, *, required: bool = False) -> str:
    """Validate metadata strings without silently converting malformed values."""
    if value is None:
        value = ""
    if not isinstance(value, str) or (required and not value.strip()):
        raise ValueError(f"Missing or invalid {label}")
    return value.strip()


def gav(record: dict[str, Any]) -> str:
    """Identify effective POM metadata independently of resolved type and classifier."""
    parts = [string(record.get(name), name, required=True) for name in ("groupId", "artifactId", "version")]
    if any(re.search(r"[:\s]", part) for part in parts):
        raise ValueError("Invalid Maven coordinate")
    return ":".join(parts)


def escaped(value: str) -> str:
    """Keep untrusted metadata literal in Markdown tables and MDX."""
    value = html.escape(" ".join(value.split()), quote=True)
    return re.sub(r"[\\`*_{}\[\]|]", lambda match: f"&#{ord(match.group())};", value)


def web_url(value: str, *, https: bool = False) -> str:
    """Return an encoded Markdown destination only for an absolute HTTP(S) URL."""
    try:
        parsed = urlsplit(value)
        valid = parsed.scheme in (("https",) if https else ("http", "https")) and bool(parsed.hostname)
    except ValueError:
        valid = False
    if not valid or re.search(r"[\x00-\x20\x7f]", value):
        raise ValueError(f"Invalid {'HTTPS' if https else 'HTTP(S)'} URL: {value}")
    return quote(value, safe=":/?#@!$&'+,;=%-._~")


def link(label: str, url: str) -> str:
    """Render a literal HTML link with a validated and attribute-escaped destination."""
    return f'<a href="{html.escape(web_url(url), quote=True)}">{escaped(label)}</a>'


def fenced(value: str) -> str:
    """Preserve source text inside a fence that cannot be closed by its contents."""
    fence = "`" * max(3, 1 + max((len(match.group()) for match in re.finditer(r"`+", value)), default=0))
    return f"{fence}text\n{value}" + ("" if value.endswith("\n") else "\n") + f"{fence}\n"


@dataclass
class Dependency:
    """One resolved identity with its graph-owned scope and directness."""

    gav: str
    kind: str
    classifier: str
    scope: str
    direct: bool

    @property
    def coordinate(self) -> str:
        """Use Maven's group:artifact:type[:classifier]:version notation."""
        group, artifact, version = self.gav.split(":")
        return ":".join(part for part in (group, artifact, self.kind, self.classifier, version) if part)


def graph(tree: dict[str, Any]) -> tuple[dict[str, Dependency], str]:
    """Read mediated paths without inheriting a parent's effective dependency scope."""
    if not isinstance(tree, dict) or tree.get("artifactId") != "cs1302-tracer":
        raise ValueError("Expected the cs1302-tracer dependency graph")
    rows: dict[str, Dependency] = {}
    lines = ["cs1302-tracer"]

    def visit(parent: dict[str, Any], depth: int) -> None:
        children = parent.get("children", [])
        if not isinstance(children, list) or any(not isinstance(child, dict) for child in children):
            raise ValueError("Dependency children must be a list of objects")
        prepared = []
        for child in children:
            dependency = Dependency(
                gav(child),
                string(child.get("type"), "resolved type", required=True),
                string(child.get("classifier"), "classifier"),
                string(child.get("scope"), "effective scope", required=True),
                depth == 1,
            )
            if dependency.scope not in GROUPS:
                raise ValueError(f"Unsupported effective scope: {dependency.scope}")
            if re.search(r"[:\s]", dependency.kind + dependency.classifier):
                raise ValueError("Invalid resolved type or classifier")
            prepared.append((dependency.coordinate, dependency, child))
        for coordinate, dependency, child in sorted(prepared, key=lambda item: item[0]):
            existing = rows.get(coordinate)
            if existing is not None:
                if existing.scope != dependency.scope:
                    raise ValueError(f"Conflicting effective scopes: {coordinate}")
                dependency.direct |= existing.direct
            rows[coordinate] = dependency
            lines.append("  " * depth + f"- {coordinate} [{dependency.scope}]")
            visit(child, depth + 1)

    visit(tree, 1)
    return rows, "\n".join(lines)


def license_pairs(value: object) -> list[tuple[str, str]]:
    """Preserve all effective POM declarations, including incomplete entries for overrides."""
    if not isinstance(value, list) or any(not isinstance(item, dict) for item in value):
        raise ValueError("Licenses must be a list of objects")
    return [(string(item.get("name"), "license name"), string(item.get("url"), "license URL")) for item in value]


def preserves(declared: list[tuple[str, str]], replacement: list[tuple[str, str]]) -> bool:
    """Match every declaration once, allowing ambiguous missing fields without dropping duplicates."""
    matched: dict[int, int] = {}

    def assign(index: int, seen: set[int]) -> bool:
        name, url = declared[index]
        for slot, pair in enumerate(replacement):
            if slot in seen or (name and pair[0] != name) or (url and pair[1] != url):
                continue
            seen.add(slot)
            if slot not in matched or assign(matched[slot], seen):
                matched[slot] = index
                return True
        return False

    return all(assign(index, set()) for index in range(len(declared)))


def licenses(record: dict[str, Any], override: object) -> tuple[str, str]:
    """Require complete declarations or an explicit, version-specific source for missing metadata."""
    declared = license_pairs(record.get("licenses", []))
    complete = bool(declared) and all(name and url for name, url in declared)
    provenance = ""
    if override is not None:
        if complete:
            raise ValueError(f"Stale license override for {gav(record)}: upstream declarations are complete")
        if not isinstance(override, dict) or set(override) != {"licenses", "source", "reason"}:
            raise ValueError("License overrides require licenses, source, and reason")
        replacement = license_pairs(override["licenses"])
        source = web_url(string(override["source"], "override source", required=True), https=True)
        reason = string(override["reason"], "override reason", required=True)
        if not preserves(declared, replacement):
            raise ValueError("License override must preserve every upstream declaration")
        declared = replacement
        provenance = (
            f"<p><strong>License metadata override:</strong> {link('Reviewed source', source)} — {escaped(reason)}</p>"
        )
    if not declared or any(not name or not url for name, url in declared):
        raise ValueError(f"Missing license name or URL for {gav(record)}")
    links = "\n".join(f"<li>{link(name, url)}</li>" for name, url in sorted(declared))
    return f'<ul class="dependency-license-list">\n{links}\n</ul>', provenance


def entry(item: Dependency, record: dict[str, Any], declared: tuple[str, str], group: str, *, qualify: bool) -> str:
    """Render one inventory entry with visible licenses and a native, uniquely named disclosure."""
    identity = "dependency-" + hashlib.sha256(item.coordinate.encode()).hexdigest()
    group_id, artifact, version = item.gav.split(":")
    relationship = "Direct" if item.direct else "Transitive"
    name = string(record.get("name"), "name") or MISSING
    description = string(record.get("description"), "description") or MISSING
    project = string(record.get("url"), "project URL")
    project_details = ""
    try:
        name_link = link(artifact, project) if project else escaped(artifact)
    except ValueError:
        name_link = escaped(artifact)
        project_details = escaped(project) + " (not an HTTP(S) link)"
    if not project:
        project_details = MISSING
    fields = (
        f"<p>{escaped(description)}</p>\n"
        f"<dl>\n<dt>Upstream project name</dt>\n<dd>{escaped(name)}</dd>\n"
        "<dt>Resolved coordinate</dt>\n"
        f'<dd><code class="dependency-coordinate">{escaped(item.coordinate)}</code></dd>\n'
        f"<dt>Artifact type</dt>\n<dd>{escaped(item.kind)}</dd>\n"
    )
    if item.classifier:
        fields += f"<dt>Classifier</dt>\n<dd>{escaped(item.classifier)}</dd>\n"
    if project_details:
        fields += f"<dt>Project website</dt>\n<dd>{project_details}</dd>\n"
    fields += "</dl>\n" + declared[1]
    override_note = (
        '<p class="dependency-override-note">Reviewed metadata override; see details.</p>\n' if declared[1] else ""
    )
    qualifier = f'<span class="dependency-group-id">{escaped(group_id)}</span>\n' if qualify else ""
    return (
        '<tbody class="dependency-entry" data-dependency-entry="true" role="rowgroup">\n'
        '<tr role="row">\n'
        f'<th id="{identity}" scope="row" role="rowheader" class="dependency-name" '
        f'headers="{group}-dependency">\n{name_link}\n{qualifier}'
        f'<span class="dependency-version">Version {escaped(version)}</span>\n</th>\n'
        f'<td class="dependency-use" headers="{identity} {group}-use" role="cell" '
        f'aria-label="Scope: {item.scope}; relationship: {relationship}">\n'
        '<span class="dependency-mobile-label" aria-hidden="true">Use</span>\n'
        f'<span class="dependency-scope">{item.scope}</span>'
        '<span class="dependency-use-separator" aria-hidden="true"> · </span>'
        f'<span class="dependency-relationship">{relationship}</span>\n'
        "</td>\n"
        f'<td class="dependency-licenses" headers="{identity} {group}-licenses" role="cell">\n'
        '<span class="dependency-mobile-label" aria-hidden="true">Declared licenses</span>\n'
        f"{declared[0]}\n{override_note}</td>\n</tr>\n"
        '<tr class="dependency-details-row" role="row">\n'
        f'<td colspan="3" headers="{identity}" role="cell">\n'
        f'<details id="{identity}-details" class="dependency-details">\n'
        f'<summary id="{identity}-summary" class="dependency-summary" '
        f'aria-label="Details for {escaped(item.coordinate)}">Details</summary>\n'
        f'<div class="dependency-metadata">\n{fields}</div>\n'
        "</details>\n</td>\n</tr>\n</tbody>\n"
    )


def pages(root: Path, tree: dict[str, Any], metadata: dict[str, Any], overrides: dict[str, Any]) -> dict[Path, str]:
    """Build both deterministic pages before changing any tracked document."""
    resolved, paths = graph(tree)
    if not isinstance(metadata, dict) or not isinstance(metadata.get("dependencies"), list):
        raise ValueError("Metadata must contain a dependency list")
    records: dict[str, dict[str, Any]] = {}
    for record in metadata["dependencies"]:
        if not isinstance(record, dict):
            raise ValueError("Dependency metadata must be an object")
        key = gav(record)
        if key in records:
            raise ValueError(f"Duplicate dependency metadata: {key}")
        records[key] = record
    expected = {dependency.gav for dependency in resolved.values()}
    if records.keys() != expected:
        raise ValueError(
            f"Maven graph/metadata mismatch: missing={sorted(expected - records.keys())}, "
            f"extra={sorted(records.keys() - expected)}"
        )
    if not isinstance(overrides, dict) or overrides.keys() - expected:
        raise ValueError("Unmatched license overrides; review them for the resolved versions")
    if any(not isinstance(value, dict) for value in overrides.values()):
        raise ValueError("License overrides must be objects")
    declared = {key: licenses(record, overrides.get(key)) for key, record in records.items()}
    artifact_counts = Counter(item.gav.split(":")[1] for item in resolved.values())
    sections = []
    jumps = []
    for group in ("Runtime", "Test", "Provided", "System"):
        selected = sorted(
            (item for item in resolved.values() if GROUPS[item.scope] == group),
            key=lambda item: (item.gav.split(":")[1].casefold(), item.coordinate),
        )
        if not selected and group in ("Provided", "System"):
            continue
        prefix = group.lower()
        anchor = f"{prefix}-dependencies"
        jumps.append(f"[{group} ({len(selected)})](#{anchor})")
        sections.append(
            f'<section class="dependency-inventory" aria-labelledby="{anchor}">\n'
            f'<h2 id="{anchor}">{group} dependencies <span class="dependency-count">({len(selected)})</span></h2>\n'
        )
        if selected:
            sections.append(
                f'<table class="dependency-table" aria-labelledby="{anchor}" role="table">\n'
                '<thead role="rowgroup">\n<tr role="row">\n'
                f'<th id="{prefix}-dependency" scope="col" role="columnheader">Dependency / version</th>\n'
                f'<th id="{prefix}-use" scope="col" role="columnheader">Use</th>\n'
                f'<th id="{prefix}-licenses" scope="col" role="columnheader">Declared licenses</th>\n'
                "</tr>\n</thead>\n"
            )
            for direct, relationship in ((True, "Direct"), (False, "Transitive")):
                subgroup = [item for item in selected if item.direct == direct]
                if not subgroup:
                    continue
                sections.append(
                    '<tbody class="dependency-subgroup" role="rowgroup">\n<tr role="row">\n'
                    '<td colspan="3" role="cell">\n'
                    f'<h3 id="{prefix}-{relationship.lower()}-dependencies">{relationship} dependencies '
                    f'<span class="dependency-count">({len(subgroup)})</span></h3>\n</td>\n</tr>\n</tbody>\n'
                )
                sections.extend(
                    entry(
                        item,
                        records[item.gav],
                        declared[item.gav],
                        prefix,
                        qualify=artifact_counts[item.gav.split(":")[1]] > 1,
                    )
                    for item in subgroup
                )
            sections.append("</table>\n")
        else:
            sections.append("<p>No resolved dependencies in this group.</p>\n")
        sections.append("</section>\n\n")
    jumps += ["[Dependency tree](#resolved-dependency-tree)", "[About this inventory](#about-this-inventory)"]
    dependency_page = (
        "---\nhide_table_of_contents: true\n---\n\n# Dependency reference\n\n" + NOTICE + "\n"
        f"{len(resolved)} resolved project dependencies for this documentation version, including tests. "
        "Versions and declared licenses are visible below. Expand **Details** "
        "for full metadata.\n\n"
        "Jump to: "
        + " · ".join(jumps)
        + "\n\n"
        + "".join(sections)
        + "## Resolved dependency tree\n\n"
        + fenced(paths)
        + "\n## About this inventory\n\n"
        "**Maven** supplies the mediated graph and effective POM metadata, including inherited license declarations.\n"
        "This inventory describes the source revision of this documentation version; retained release snapshots\n"
        "preserve their own inventory. Each entry identifies a resolved group, artifact, type, optional classifier,\n"
        "and version. Effective scope and type come from that graph node, not its parent or the dependency POM's\n"
        "packaging. Runtime groups `compile` and `runtime`; Test contains `test`. Provided and system dependencies\n"
        "appear separately when present. Direct dependencies are declared by this project; transitive dependencies\n"
        "are brought in through other project dependencies.\n\n"
        "Entries show artifact IDs, with group IDs when an artifact ID repeats. Full upstream project names and\n"
        "resolved coordinates remain in Details. Direct dependencies appear first; each subgroup is sorted by\n"
        "artifact ID, with full coordinates breaking ties.\n\n"
        "This inventory excludes build plugins, annotation processors configured outside the project dependency\n"
        "graph, and the documentation/tooling **npm** and Python environments. "
        "It is not an inventory of every build tool.\n"
        "License names and URLs reproduce all upstream declarations without inferring an AND/OR relationship.\n"
        "A metadata override fills missing licensing information only and identifies its reviewed source and reason\n"
        "in the entry's details. Missing descriptive fields are labeled explicitly; they are not invented.\n\n"
        "The tree shows Maven's mediated representative paths, not every possible dependency path "
        "or omitted conflict.\n"
        "Node labels retain their own effective scopes; indentation does not determine scope. "
        "The root label is stable\n"
        "across project release-version transitions.\n\n"
        "See the [project license](licenses.md) and the\n"
        "[maintenance instructions]"
        "(../contributing/documentation-authoring.md#maintain-license-and-dependency-pages).\n"
    )
    license_page = (
        "# Project license\n\n" + NOTICE + "\n"
        "The first-party cs1302-tracer code and documentation are distributed under the MIT License.\n"
        "The complete text below is copied from the repository's\n"
        "`LICENSE` file. This project license does not replace the licenses of third-party dependencies; see the\n"
        "[dependency reference](dependencies.md) for their resolved versions and declared licenses.\n\n"
        + fenced((root / "LICENSE").read_text(encoding="utf-8", newline=""))
    )
    return {root / "docs/reference/licenses.md": license_page, root / "docs/reference/dependencies.md": dependency_page}


def main() -> None:
    """Resolve fresh inputs once, then update both pages or reject any drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("update", "check"))
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="tracer-dependency-docs-") as temporary:
        output = Path(temporary)
        subprocess.run(
            [
                str(ROOT / "mvnw"),
                "-B",
                "-ntp",
                "dependency:tree",
                "license:add-third-party@dependency-docs",
                "-DoutputType=json",
                f"-DoutputFile={output / 'tree.json'}",
                f"-Ddependency.docs.outputDirectory={output}",
            ],
            cwd=ROOT,
            check=True,
        )
        override_path = ROOT / "scripts/dependency-license-overrides.json"
        overrides = json.loads(override_path.read_text(encoding="utf-8")) if override_path.exists() else {}
        rendered = pages(
            ROOT,
            json.loads((output / "tree.json").read_text(encoding="utf-8")),
            json.loads((output / "metadata.json").read_text(encoding="utf-8")),
            overrides,
        )
    errors = []
    for path, content in rendered.items():
        if args.action == "update":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="")
        else:
            current = path.read_text(encoding="utf-8", newline="") if path.exists() else ""
            if current != content:
                errors.append(
                    "".join(
                        difflib.unified_diff(
                            current.splitlines(True),
                            content.splitlines(True),
                            fromfile=str(path.relative_to(ROOT)),
                            tofile="generated",
                        )
                    )
                )
    if errors:
        raise SystemExit("".join(errors) + "Run ./scripts/uv run python scripts/dependency_docs.py update\n")
    print(f"License and dependency pages {'updated' if args.action == 'update' else 'checked'}.")


if __name__ == "__main__":
    main()
